function toSlug(brand: string, name: string, id: string): string {
  return `${brand}-${name}-${id}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "");
}

export const marketplaceListings: MarketplaceListing[] = listingsRaw.map(
  (item) => ({
    ...item,
    slug: toSlug(item.brand, item.name, item.id),
  }),
);

export function getSellerById(id: string): MarketplaceSeller | undefined {
  return marketplaceSellers.find((s) => s.id === id);
}

export function getListingById(id: string): MarketplaceListing | undefined {
  return marketplaceListings.find((l) => l.id === id || l.slug === id);
}

export function getActiveListings(): MarketplaceListing[] {
  return marketplaceListings.filter((l) => l.status === "active");
}

export function getListingsBySeller(sellerId: string): MarketplaceListing[] {
  return marketplaceListings.filter((l) => l.sellerId === sellerId);
}

export function getNewDrops(limit = 8): MarketplaceListing[] {
  return [...getActiveListings()]
    .sort(
      (a, b) =>
        new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime(),
    )
    .slice(0, limit);
}

export function getTrending(limit = 8): MarketplaceListing[] {
  return [...getActiveListings()]
    .sort((a, b) => b.views - a.views)
    .slice(0, limit);
}
